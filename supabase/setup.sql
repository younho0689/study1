create table if not exists public.rest_area_inspections (
  id bigint generated by default as identity primary key,
  rest_area_name text not null,
  route text not null,
  inspection_date date not null,
  status text not null check (status in ('정상', '점검 필요', '점검 예정')),
  note text not null default ''
);

-- 공개 서비스에서는 행 단위 보안을 반드시 켭니다.
alter table public.rest_area_inspections enable row level security;

-- 실습용 방문자(anon)에게 조회 외 작업 권한을 주지 않습니다.
revoke all on table public.rest_area_inspections from anon, authenticated;
grant select on table public.rest_area_inspections to anon;

-- 정책을 중복 생성하지 않도록 기존 같은 이름만 삭제한 뒤 추가합니다.
drop policy if exists "lab_public_read_only" on public.rest_area_inspections;
create policy "lab_public_read_only"
  on public.rest_area_inspections
  for select
  to anon
  using (true);

